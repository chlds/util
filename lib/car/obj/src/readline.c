# define CAR_H
# include "./../../../config.h"

signed *(__cdecl readline(signed(args/*desc*/),signed(argp/*line*/))) {
auto signed *ldg;
auto signed r;
if(!(0x00<(carl(argp)))) return(0x00);
ldg = chainage_xe(readk(args));
if(!(0x01<(couni(ldg)))) return(ldg); // absorbing the runt or just null
if(!(0x01+(cseek(args,cii_xe(runt(ldg)))))) return(burn(ldg));
argp = addh_xe(argp,couni(ldg));
r = carl(argp);
if(r<(carh(argp))) return(ldg);
return(catalystr_xxe(ldg,readline(args,argp)));
}
