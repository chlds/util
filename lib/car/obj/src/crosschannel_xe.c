signed char *(__cdecl crosschannel_xe(signed char(*args),signed char(*argp))) {
auto signed r;
r = charle(argp);
if(!(r<(channelwidth()))) return(argp);
if(coex(args,argp)) return(argp);
argp = lethe(argp);
argp = casca_b(++r,args);
if(!argp) return(argp);
return(crosschannel_xe(args,argp));
}
